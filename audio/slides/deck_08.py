def strip(n, bad=(), color=RED, w=0.27, gap=0.06, x=0, y=0, labels=None, good=None):
    """A row of n cells, one per challenge value, with the bad values filled."""
    cells = VGroup()
    for k in range(n):
        filled = k in bad
        sq = Square(w, stroke_color=color if filled else LINE, stroke_width=1.5,
                    fill_color=color if filled else (good or WHITE), fill_opacity=1 if filled else (0.25 if good else 1))
        cells.add(sq)
    cells.arrange(RIGHT, buff=gap)
    at(cells, x, y)
    return cells


def lanes(y=2.2, x=5.4):
    """Prover and verifier headers with lifelines."""
    p = at(card("Prover", 2.6, 0.75, BLUE, 26), -x, y)
    v = at(card("Verifier", 2.6, 0.75, TEAL, 26), x, y)
    lp = DashedLine(p.get_bottom(), [-x, -3.3, 0], color=LINE, stroke_width=2)
    lv = DashedLine(v.get_bottom(), [x, -3.3, 0], color=LINE, stroke_width=2)
    return VGroup(p, v, lp, lv)


def msg(k, text, to_v=True, color=INK, y0=1.15, dy=0.78, x=5.4, size=24):
    """Message k between the lanes, with its label above the arrow."""
    yy = y0 - k * dy
    a, b = ([-x + 0.1, yy, 0], [x - 0.1, yy, 0]) if to_v else ([x - 0.1, yy, 0], [-x + 0.1, yy, 0])
    ar = Arrow(a, b, buff=0, color=color if color != INK else MUTED, stroke_width=3, tip_length=0.18,
               max_tip_length_to_length_ratio=0.05)
    lab = at(code(text, size, color), 0, yy + 0.26)
    return VGroup(ar, lab)


def side_note(text, k, right=False, color=MUTED, y0=1.15, dy=0.78, size=22):
    yy = y0 - k * dy
    t = T(text, size, color)
    return at(t, (6.2 - t.width / 2) if right else (-6.2 + t.width / 2), yy - 0.05)


def grid(cols, rows, marks, x=0, y=0, dx=1.5, dy=0.75, color=BLUE, size=24):
    """Polynomials against points, with a dot where a claim sits."""
    head = VGroup(*[at(T(str(c), size, MUTED, True), x + (j - (len(cols) - 1) / 2) * dx, y + dy) for j, c in enumerate(cols)])
    names = VGroup(*[at(code(r, size, INK), x - (len(cols) + 1) / 2 * dx, y - i * dy) for i, r in enumerate(rows)])
    dots = VGroup(*[at(Dot(radius=0.13, color=color), x + (j - (len(cols) - 1) / 2) * dx, y - i * dy) for i, j in marks])
    return head, names, dots


def table(rows, widths, x=0, y=1.8, h=0.62, size=24, head_color=BLUE, colors=None):
    """A small table; the first row is the header."""
    out = VGroup()
    total = sum(widths)
    for r, row in enumerate(rows):
        cells = VGroup()
        cx = x - total / 2
        for c, (text, w) in enumerate(zip(row, widths)):
            col = head_color if r == 0 else (colors[r][c] if colors and colors.get(r) and colors[r][c] else INK)
            t = (T(text, size, col, True) if r == 0 else code(text, size, col))
            if t.width > w - 0.15:
                t.scale_to_fit_width(w - 0.15)
            at(t, cx + w / 2, y - r * h)
            cells.add(t)
            cx += w
        out.add(cells)
    rule = Line([x - total / 2, y - h / 2, 0], [x + total / 2, y - h / 2, 0], color=LINE, stroke_width=2)
    return out, rule



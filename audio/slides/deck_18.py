def stage_tree(x0=-7.2, y0=2.25, dy=0.5, dx=0.62):
    """The native stage tree, indented by depth. Returns name -> chip and the connectors."""
    nodes, stack, lines = {}, [], VGroup()
    for i, (name, d) in enumerate(TREE):
        c = chip(name, BLUE, h=0.44, size=22)
        c.move_to([x0 + d * dx + c.width / 2, y0 - i * dy, 0])
        nodes[name] = c
        stack = stack[:d]
        if stack:
            p = nodes[stack[-1]]
            px = p.get_left()[0] + 0.22
            pts_ = [[px, p.get_bottom()[1], 0], [px, c.get_y(), 0], [c.get_left()[0], c.get_y(), 0]]
            lines.add(VMobject(color=LINE, stroke_width=3).set_points_as_corners(pts_))
        stack.append(name)
    return nodes, lines



def cards(first, title, items, sub=None, w=None, h=2.3, size=26, y=-0.3, note=None):
    """A row of colored cards, given as (text, color) pairs, arriving one at a time."""
    @slide(first, title, sub)
    def build(s):
        width = w or min(4.6, (14.6 - 0.35 * (len(items) - 1)) / len(items))
        row = VGroup(*[card(t, width, h, c, size) for t, c in items]).arrange(RIGHT, buff=0.35)
        at(row, 0, y)
        for k, c in enumerate(row):
            extra = [FadeIn(caption(note, y=y - h / 2 - 0.8, color=INK, size=27, chars=78))] if note and k == len(row) - 1 else []
            yield [FadeIn(c, shift=UP * 0.2), *extra]
    return build



# Anchor rail: entry anchors of epochs 3..7, with stamps inside each epoch.
EPOCH_X = {3: -6.6, 4: -3.9, 5: -1.2, 6: 1.5, 7: 4.2}
STAMPS = {3: 3, 4: 2, 5: 1, 6: 0, 7: 3}
ENTRY = {3: "10108", 4: "63008", 5: "58408", 6: "23281", 7: "45926"}


def stamp_x(e, k):
    """x of the anchor after stamp k (1-based) of epoch e."""
    return EPOCH_X[e] + 2.7 * k / (STAMPS[e] + 1) if e < 7 else EPOCH_X[7] + 0.8 * k


def rail(y=-0.4, values=True):
    line = Line([-7.1, y, 0], [7.1, y, 0], color=LINE, stroke_width=5)
    g = VGroup(line)
    for e, x in EPOCH_X.items():
        g.add(Line([x, y - 0.32, 0], [x, y + 0.32, 0], color=INK, stroke_width=4))
        g.add(T(f"epoch {e}", 22, MUTED).move_to([x + 1.2 if e < 7 else x + 1.3, y - 0.65, 0]))
        if values:
            g.add(T(ENTRY[e], 20, INK, font=MONO).move_to([x, y + 0.55, 0]))
        for k in range(1, STAMPS[e] + 1):
            g.add(Dot([stamp_x(e, k), y, 0], radius=0.08, color=MUTED))
    return g



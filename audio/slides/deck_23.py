def at(mob, x, y):
    return mob.move_to([x, y, 0])


def pts(first, title, items, sub=None, chars=56, size=31, y=None, gap=0.42):
    """A slide whose points arrive one at a time."""
    @slide(first, title, sub)
    def build(s):
        rows = bullets(items, chars, size, gap=gap)
        rows.move_to([-7.0 + rows.width / 2, (0 if sub is None else -0.3) if y is None else y, 0])
        for row in rows:
            yield [FadeIn(row, shift=RIGHT * 0.15)]
    return build


def cards(first, title, items, sub=None, w=None, h=2.3, size=26, y=-0.3, note=None):
    """A row of colored cards, given as (text, color) pairs, arriving one at a time."""
    @slide(first, title, sub)
    def build(s):
        width = w or min(4.6, (14.6 - 0.35 * (len(items) - 1)) / len(items))
        row = VGroup(*[card(t, width, h, c, size) for t, c in items]).arrange(RIGHT, buff=0.35)
        at(row, 0, y)
        for c in row:
            yield [FadeIn(c, shift=UP * 0.2)]
        if note:
            yield [FadeIn(caption(note, y=y - h / 2 - 0.8, color=INK, size=27, chars=78))]
    return build


def flow(left, right, name, out, wit=None, y=0.4, color=ORANGE, sw=3.6, lc=BLUE, rc=BLUE, oc=BLUE):
    """Two input chips, a step card, an optional witness, and an output chip."""
    l = at(chip(left, lc, size=23), -5.2, y + 0.85)
    r = at(chip(right, rc, size=23), -5.2, y - 0.85)
    st = at(card(name, sw, 1.4, color, 28, bold=True), 0, y)
    o = at(chip(out, oc, size=23), 5.1, y)
    parts = {"l": l, "r": r, "st": st, "o": o}
    parts["in"] = [FadeIn(l), FadeIn(r), FadeIn(st), GrowArrow(arrow(l, st)), GrowArrow(arrow(r, st))]
    if wit:
        w = at(chip(wit, PURPLE, size=22), 0, y - 1.55)
        parts["w"] = w
        parts["wit"] = [FadeIn(w), GrowArrow(arrow(w, st))]
    else:
        parts["wit"] = []
    parts["out"] = [GrowArrow(arrow(st, o)), FadeIn(o)]
    return parts


class Axis(VGroup):
    """A number line drawn with plain text labels (no LaTeX)."""

    def __init__(self, lo, hi, step, length, y, size=24):
        super().__init__()
        self.lo, self.hi, self.length, self.y = lo, hi, length, y
        self.add(Line([-length / 2, y, 0], [length / 2, y, 0], color=INK, stroke_width=3))
        v = lo
        while v <= hi:
            x = self.x(v)
            self.add(Line([x, y - 0.1, 0], [x, y + 0.1, 0], color=INK, stroke_width=3))
            self.add(T(str(v), size, INK).move_to([x, y - 0.4, 0]))
            v += step

    def x(self, v):
        return -self.length / 2 + self.length * (v - self.lo) / (self.hi - self.lo)

    def n2p(self, v):
        return np.array([self.x(v), self.y, 0])



def at(mob, x, y):
    return mob.move_to([x, y, 0])


def pts(first, title, items, sub=None, chars=56, size=31, y=None, gap=0.42):
    """A slide whose points arrive one at a time."""
    @slide(first, title, sub)
    def build(s):
        rows = bullets(items, chars, size, gap=gap)
        rows.move_to([-7.0 + rows.width / 2, -0.3 if y is None else y, 0])
        for row in rows:
            yield [FadeIn(row, shift=RIGHT * 0.15)]
    return build


def eq(text, size=30, color=INK):
    """A formula in monospace."""
    return code(text, size, color)


def vec(vals, color=BLUE, w=0.9, size=28, gap=0.12, split=True):
    """A list as a row of boxes, with a gap between the lower and upper halves."""
    boxes = VGroup(*[card(str(v), w, w * 0.82, color, size) for v in vals]).arrange(RIGHT, buff=gap)
    if split and len(vals) > 1:
        for b in boxes[len(vals) // 2:]:
            b.shift(RIGHT * 0.3)
    return boxes


def named(label, mob, color=INK, size=26, buff=0.3):
    """A label to the left of a mobject."""
    t = T(label, size, color, True).next_to(mob, LEFT, buff=buff)
    return t


def pt(text, color=BLUE, size=24):
    return chip(text, color, size=size)


def party(name, color, x, y=1.7, w=2.8):
    return at(card(name, w, 0.9, color, 28, bold=True), x, y)


def msg(x0, x1, y, label, color=INK, size=24):
    """A labelled arrow between two parties."""
    a = Arrow([x0, y, 0], [x1, y, 0], buff=0, color=color, stroke_width=4, tip_length=0.2)
    t = T(label, size, color).next_to(a, UP, buff=0.08)
    return VGroup(a, t)


def table(rows, widths, size=24, rh=0.55, head=True, colors=None):
    """Left-aligned text rows; the first row is a header when head is set."""
    out = VGroup()
    for r, row in enumerate(rows):
        x = 0
        cells = VGroup()
        for c, (txt, wd) in enumerate(zip(row, widths)):
            col = MUTED if head and r == 0 else (colors[r][c] if colors else INK)
            t = T(txt, size, col, head and r == 0)
            t.move_to([x + t.width / 2, -r * rh, 0])
            cells.add(t)
            x += wd
        out.add(cells)
    return out


def grid(cells, colors, w=3.0, h=0.95, size=24, rows=("a lo", "a hi"), cols=("G lo", "G hi")):
    """The two-by-two grid of inner products between halves."""
    boxes = VGroup()
    for r in range(2):
        for c in range(2):
            boxes.add(at(card(cells[r][c], w, h, colors[r][c], size), c * (w + 0.2), -r * (h + 0.2)))
    rl = VGroup(*[T(rows[r], 24, ORANGE, True).next_to(boxes[2 * r], LEFT, buff=0.25) for r in range(2)])
    cl = VGroup(*[T(cols[c], 24, BLUE, True).next_to(boxes[c], UP, buff=0.18) for c in range(2)])
    return VGroup(boxes, rl, cl)



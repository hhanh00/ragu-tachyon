def split_bar(y=0.0, total=12.0, short=2.0, h=0.9, text=("instance", "witness"), x0=None):
    """A bar divided into a short BLUE part and a long ORANGE part."""
    x0 = -total / 2 if x0 is None else x0
    a = Rectangle(width=short, height=h, stroke_color=BLUE, stroke_width=2.5, fill_color=BLUE, fill_opacity=0.15)
    b = Rectangle(width=total - short, height=h, stroke_color=ORANGE, stroke_width=2.5, fill_color=ORANGE, fill_opacity=0.12)
    a.move_to([x0 + short / 2, y, 0])
    b.move_to([x0 + short + (total - short) / 2, y, 0])
    ta = T(text[0], 24, BLUE, True).move_to(a)
    tb = T(text[1], 24, ORANGE, True).move_to(b)
    return VGroup(VGroup(a, ta), VGroup(b, tb))


def boxed(title, body, color, w=4.4, h=2.2, tsize=27, bsize=23, chars=30):
    box = card(None, w, h, color)
    t = T(title, tsize, color, True).move_to(box).shift(UP * (h / 2 - 0.38))
    b = W(body, chars, bsize, INK, align=ORIGIN).move_to(box).shift(DOWN * 0.22)
    return VGroup(box, t, b)


def table(rows, xs, y0, dy=0.52, size=22, colors=None, font=MONO):
    """Rows of strings placed at column centers xs. Returns a VGroup of row VGroups."""
    out = VGroup()
    for r, row in enumerate(rows):
        g = VGroup()
        for c, cell in enumerate(row):
            col = (colors[c] if colors else INK) if r else MUTED
            g.add(at(T(str(cell), size, col, r == 0, font=FONT if r == 0 else font), xs[c], y0 - r * dy))
        out.add(g)
    return out



def step_rows(sorted_=False, show_cost=False):
    rows = VGroup()
    for i, (name, cost, lin) in enumerate(STEPS):
        r = VGroup(T(name, 24, INK))
        if show_cost:
            r.add(T(cost, 22, BLUE if not lin else ORANGE).next_to(r[0], RIGHT, buff=0.35))
        rows.add(r)
    for i, r in enumerate(rows):
        lin = STEPS[i][2]
        if sorted_:
            k = i if not lin else i - 4
            at(r, (-3.9 if not lin else 3.6), 1.4 - k * 0.75)
        else:
            order = [4, 0, 6, 2, 5, 1, 7, 3][i]
            at(r, 0, 2.15 - order * 0.6)
    return rows



def lanes(n=3, y_top=1.0, y_bot=-1.6, x0=-4.4, dx=3.0):
    """The two-lane picture: Acc.V boxes in circuits above, Acc.P boxes below, decider at the end."""
    vs = [at(card("Acc.V\nin circuit", 2.2, 1.1, BLUE, 22), x0 + k * dx, y_top) for k in range(n)]
    ps = [at(card("Acc.P\noutside", 2.2, 1.1, ORANGE, 22), x0 + k * dx, y_bot) for k in range(n)]
    dec = at(card("Decider", 2.0, 1.4, TEAL, 24), x0 + n * dx, (y_top + y_bot) / 2)
    top = [arrow(vs[k], vs[k + 1], BLUE) for k in range(n - 1)] + [arrow(vs[-1].get_right(), dec.get_left() + UP * 0.3, BLUE)]
    bot = [arrow(ps[k], ps[k + 1], ORANGE) for k in range(n - 1)] + [arrow(ps[-1].get_right(), dec.get_left() + DOWN * 0.3, ORANGE)]
    up = [arrow(p.get_top(), v.get_bottom(), MUTED) for p, v in zip(ps, vs)]
    return vs, ps, dec, top, bot, up



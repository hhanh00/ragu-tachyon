def bitrow(bits, size=34, colors=None, box=0.62):
    """A bit string as boxes, first bit on the left."""
    g = VGroup()
    for k, b in enumerate(bits):
        col = colors[k] if colors else INK
        sq = Square(box, stroke_color=col, stroke_width=2.5, fill_color=col, fill_opacity=0.08)
        g.add(VGroup(sq, code(b, size, col).move_to(sq)))
    return g.arrange(RIGHT, buff=0.08)


def bit_colors(n):
    return [MUTED, MUTED] + [INK] * (n - 2)


def brace_label(mob, text, color=MUTED, size=22):
    br = Brace(mob, DOWN, color=color, buff=0.08)
    return VGroup(br, T(text, size, color).next_to(br, DOWN, buff=0.08))



# The toy curve E: y^2 = x^3 + 3 over the field of size 31, plotted for the endomorphism slides.
E_POINTS = [(x, y) for x in range(31) for y in range(31) if (y * y - x ** 3 - 3) % 31 == 0]


def plot_frame(cx=-3.4, cy=-0.4, size=5.4):
    box = Square(size, stroke_color=LINE, stroke_width=2)
    at(box, cx, cy)
    k = size / 31

    def place(x, y):
        return [cx - size / 2 + (x + 0.5) * k, cy - size / 2 + (y + 0.5) * k, 0]
    lab = T("toy curve, coordinates mod 31", 22, MUTED).next_to(box, DOWN, buff=0.12)
    return box, place, lab


def curve_dots(place, color=ORANGE, r=0.06):
    return VGroup(*[Dot(place(x, y), radius=r, color=color) for x, y in E_POINTS])



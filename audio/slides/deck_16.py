def at(mob, x, y):
    return mob.move_to([x, y, 0])


def fit(mob, w=14.6):
    if mob.width > w:
        mob.scale_to_fit_width(w)
    return mob


def cap(text, y=-3.3, color=INK, size=28, chars=72):
    return caption(text, y=y, color=color, size=size, chars=chars)


def M(text, size=32, color=INK):
    """A formula line in monospace."""
    return code(text, size, color)


def pts(first, title, items, sub=None, chars=56, size=30, y=None, gap=0.42):
    """A slide whose points arrive one at a time."""
    @slide(first, title, sub)
    def build(s):
        rows = bullets(items, chars, size, gap=gap)
        rows.move_to([-7.0 + rows.width / 2, -0.3 if y is None else y, 0])
        for row in rows:
            yield [FadeIn(row, shift=RIGHT * 0.15)]
    return build


def flow(first, title, items, sub=None, y=0.0, h=1.7, size=26, note=None, note_color=INK):
    """Cards joined left to right by arrows, each arriving with its arrow."""
    @slide(first, title, sub)
    def build(s):
        n = len(items)
        w = min(4.4, (14.4 - 0.75 * (n - 1)) / n)
        row = VGroup(*[card(t, w, h, c, size) for t, c in items]).arrange(RIGHT, buff=0.75)
        at(row, 0, y)
        yield [FadeIn(row[0], shift=UP * 0.2)]
        for a, b in zip(row, row[1:]):
            yield [GrowArrow(arrow(a, b)), FadeIn(b, shift=UP * 0.2)]
        if note:
            yield [FadeIn(cap(note, y=y - h / 2 - 0.9, color=note_color))]
    return build


def eqs(first, title, lines, sub=None, size=34, y=None, gap=0.55, note=None, note_color=INK):
    """Formula lines, given as (text, color), arriving one per step."""
    @slide(first, title, sub)
    def build(s):
        rows = VGroup(*[M(t, size, c) for t, c in lines]).arrange(DOWN, buff=gap, aligned_edge=LEFT)
        fit(rows)
        at(rows, 0, 0.6 if y is None else y)
        for r in rows:
            yield [FadeIn(r, shift=RIGHT * 0.15)]
        if note:
            yield [FadeIn(cap(note, y=-3.1, color=note_color))]
    return build


def grid(head, rows, widths, size=24, rh=0.62):
    """A table as rows of text cells. Returns (header row, body rows)."""
    def make(cells, color, bold):
        g = VGroup()
        x = 0
        for c, w in zip(cells, widths):
            col = color if isinstance(c, str) else c[1]
            txt = c if isinstance(c, str) else c[0]
            t = T(txt, size, col, bold) if not txt.startswith("`") else code(txt[1:], size, col)
            if t.width > w - 0.15:
                t.scale_to_fit_width(w - 0.15)
            t.move_to([x + w / 2, 0, 0])
            g.add(t)
            x += w
        return g
    hdr_row = make(head, MUTED, True)
    body = [make(r, INK, False) for r in rows]
    allrows = VGroup(hdr_row, *body)
    for k, r in enumerate(allrows):
        r.shift(DOWN * k * rh)
    line = Line([0, -rh / 2, 0], [sum(widths), -rh / 2, 0], color=LINE, stroke_width=2)
    return VGroup(hdr_row, line), body


def table(first, title, head, rows, widths, sub=None, size=24, y=1.6, note=None, note_color=INK, steps=None, rh=0.62):
    @slide(first, title, sub)
    def build(s):
        h, body = grid(head, rows, widths, size, rh)
        whole = VGroup(h, *body)
        whole.shift([-sum(widths) / 2, y, 0])
        groups = steps or [[i] for i in range(len(body))]
        yield [FadeIn(h), *[FadeIn(body[i]) for i in groups[0]]]
        for g in groups[1:]:
            yield [*[FadeIn(body[i], shift=DOWN * 0.1) for i in g]]
        if note:
            yield [FadeIn(cap(note, color=note_color))]
    return build


def bar_rows(items, maxv, length=8.0, size=24, gap=0.75, x0=-2.6):
    """Horizontal bars: (label, value, color, shown text)."""
    rows = VGroup()
    for k, (label, v, color, shown) in enumerate(items):
        lab = W(label, 24, size, INK, align=RIGHT)
        lab.move_to([x0 - 0.3 - lab.width / 2, -k * gap, 0])
        L = max(0.06, length * v / maxv)
        bar = Rectangle(width=L, height=0.42, stroke_width=0, fill_color=color, fill_opacity=0.85)
        bar.move_to([x0 + L / 2, -k * gap, 0])
        val = T(shown, size, color, True).next_to(bar, RIGHT, buff=0.18)
        rows.add(VGroup(lab, bar, val))
    return rows


def bars(first, title, items, maxv, sub=None, y=1.2, gap=0.85, note=None, note_color=INK, steps=None, x0=-2.6, length=8.0):
    @slide(first, title, sub)
    def build(s):
        rows = bar_rows(items, maxv, gap=gap, x0=x0, length=length)
        rows.shift(UP * y)
        groups = steps or [[i] for i in range(len(rows))]
        for g in groups:
            anims = []
            for i in g:
                lab, bar, val = rows[i]
                anims += [FadeIn(lab), GrowFromEdge(bar, LEFT), FadeIn(val)]
            yield anims
        if note:
            yield [FadeIn(cap(note, color=note_color))]
    return build



def seg_row(items, w, y, x0=-7.3, h=1.1, size=22, plain=False):
    row = VGroup()
    x = x0
    for text, c in items:
        ww = w if not isinstance(w, list) else w[len(row)]
        row.add(at(card(text, ww, h, MUTED if plain else c, size), x + ww / 2, y))
        x += ww + 0.08
    return row



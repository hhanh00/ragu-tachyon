def at(mob, x, y):
    return mob.move_to([x, y, 0])


def pts(first, title, items, sub=None, chars=56, size=31, y=None, gap=0.42):
    """A slide whose points arrive one at a time."""
    @slide(first, title, sub)
    def build(s):
        rows = bullets(items, chars, size, gap=gap)
        rows.move_to([-7.0 + rows.width / 2, -0.3 if y is None else y, 0])
        for row in rows:
            yield [FadeIn(row, shift=RIGHT * 0.15)]
    return build


def cards(first, title, items, sub=None, w=None, h=2.3, size=26, y=-0.3, note=None):
    """A row of colored cards, given as (text, color) pairs, arriving one at a time."""
    @slide(first, title, sub)
    def build(s):
        width = w or min(4.6, (14.6 - 0.35 * (len(items) - 1)) / len(items))
        row = VGroup(*[card(t, width, h, c, size) for t, c in items]).arrange(RIGHT, buff=0.35)
        at(row, 0, y)
        for c in row:
            yield [FadeIn(c, shift=UP * 0.2)]
        if note:
            yield [FadeIn(caption(note, y=y - h / 2 - 0.85, color=INK, size=27, chars=78))]
    return build


def vs(first, title, left, right, sub=None, note=None, h=2.6, size=25, y=0.0):
    """Two sources side by side, given as (text, color) pairs."""
    @slide(first, title, sub)
    def build(s):
        a = at(card(left[0], 6.8, h, left[1], size), -3.65, y)
        b = at(card(right[0], 6.8, h, right[1], size), 3.65, y)
        yield [FadeIn(a, shift=UP * 0.2)]
        yield [FadeIn(b, shift=UP * 0.2)]
        if note:
            yield [FadeIn(caption(note, y=y - h / 2 - 0.8, color=INK, size=27, chars=74))]
    return build


def tbl(head, rows, xs, y0, dy=0.62, size=25, hsize=22, colors=None):
    """A table: a header row and data rows, each a VGroup of cells centered at xs."""
    h = VGroup(*[at(T(t, hsize, MUTED, True), x, y0) for t, x in zip(head, xs)])
    out = []
    for i, r in enumerate(rows):
        c = colors[i] if colors else INK
        out.append(VGroup(*[at(T(str(v), size, c if k == 0 else INK, k == 0), x, y0 - (i + 1) * dy) for k, (v, x) in enumerate(zip(r, xs))]))
    return h, out



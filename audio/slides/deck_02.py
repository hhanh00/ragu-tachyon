def pts(first, title, items, sub=None, chars=56, size=32, y=None, gap=0.42):
    """A slide whose points arrive one at a time."""
    @slide(first, title, sub)
    def build(s):
        rows = bullets(items, chars, size, gap=gap)
        rows.move_to([-7.0 + rows.width / 2, 0 if y is None else y, 0])
        for row in rows:
            yield [FadeIn(row, shift=RIGHT * 0.15)]
    return build


def cards(first, title, items, sub=None, w=None, h=2.3, size=27, y=-0.3, note=None):
    """A row of colored cards, given as (text, color) pairs, arriving one at a time."""
    @slide(first, title, sub)
    def build(s):
        width = w or min(4.6, (14.6 - 0.35 * (len(items) - 1)) / len(items))
        row = VGroup(*[card(t, width, h, c, size) for t, c in items]).arrange(RIGHT, buff=0.35)
        at(row, 0, y)
        for c in row:
            yield [FadeIn(c, shift=UP * 0.2)]
        if note:
            yield [FadeIn(caption(note, y=y - h / 2 - 0.85, color=INK, size=28, chars=78))]
    return build


def hdr(l, h, s, color=BLUE, size=22):
    """A toy header (start, end, sum)."""
    return chip(f"({l}, {h}, {s})", color, size=size)


def toy_tree(y0=-2.55, dy=1.45, dx=1.82, size=17):
    """The balanced tree over the toy list: header levels, chips per level, and edges."""
    levels = [[(i, i + 1, v) for i, v in enumerate(VALUES)]]
    while len(levels[-1]) > 1:
        prev = levels[-1]
        levels.append([(prev[k][0], prev[k + 1][1], prev[k][2] + prev[k + 1][2]) for k in range(0, len(prev), 2)])
    nodes, edges = [], VGroup()
    for d, level in enumerate(levels):
        row = []
        for k, h in enumerate(level):
            x = (k - 3.5) * dx if d == 0 else (nodes[d - 1][2 * k].get_x() + nodes[d - 1][2 * k + 1].get_x()) / 2
            c = at(hdr(*h, size=size), x, y0 + d * dy)
            row.append(c)
            if d:
                for child in (nodes[d - 1][2 * k], nodes[d - 1][2 * k + 1]):
                    edges.add(Line(child.get_top(), c.get_bottom(), color=LINE, stroke_width=3))
        nodes.append(row)
    return levels, nodes, edges


def value_row(y=0.6, w=1.15, size=34, show_pos=True):
    """The toy list as a row of boxes, with positions underneath."""
    boxes = VGroup(*[card(str(v), w, w, BLUE, size) for v in VALUES]).arrange(RIGHT, buff=0.22)
    at(boxes, 0, y)
    pos = VGroup(*[T(str(i), 22, MUTED).next_to(b, DOWN, buff=0.15) for i, b in enumerate(boxes)])
    return boxes, pos


def proof_tree(y=-2.2, color=ORANGE, label="proof"):
    """Four leaf proofs combining into one at the top."""
    leaves = at(VGroup(*[card(label, 2, 0.85, color, 24) for _ in range(4)]).arrange(RIGHT, buff=0.6), 0, y)
    mid = [at(card(label, 2, 0.85, color, 24), (leaves[i].get_x() + leaves[i + 1].get_x()) / 2, y + 1.6) for i in (0, 2)]
    top = at(card(label, 2, 0.85, color, 24), 0, y + 3.2)
    up1 = [arrow(leaves[i], mid[i // 2]) for i in range(4)]
    up2 = [arrow(m, top) for m in mid]
    return leaves, mid, top, up1, up2



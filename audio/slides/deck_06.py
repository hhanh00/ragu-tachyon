def curve_points():
    pts_ = []
    for x in range(31):
        for yy in range(31):
            if (yy * yy - x ** 3 - 3) % 31 == 0:
                pts_.append((x, yy))
    return pts_


def curve_grid(cx=-2.6, cy=-0.75, size=5.6):
    """All affine points of y^2 = x^3 + 3 over F_31 in a square grid."""
    frame = Square(side_length=size, color=LINE, stroke_width=2)
    at(frame, cx, cy)
    step = size / 31

    def place(x, yy):
        return [cx - size / 2 + (x + 0.5) * step, cy - size / 2 + (yy + 0.5) * step, 0]

    dots = VGroup(*[Dot(place(x, yy), radius=0.07, color=MUTED) for x, yy in curve_points()])
    return frame, dots, place



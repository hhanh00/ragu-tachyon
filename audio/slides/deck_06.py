def table(rows, xs, y0, dy=0.62, size=25, head_color=MUTED):
    """Rows of strings laid out at the given column centers; the first row is a header."""
    out = VGroup()
    for r, row in enumerate(rows):
        cells = VGroup(*[at(T(c, size, head_color if r == 0 else INK, r == 0, font=FONT if r == 0 else MONO), x, y0 - r * dy)
                         for c, x in zip(row, xs)])
        out.add(cells)
    return out



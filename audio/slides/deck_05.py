def at(mob, x, y):
    return mob.move_to([x, y, 0])


def sup(n):
    return str(n).translate(SUP)


def poly(coeffs, var="X"):
    """A polynomial as text, lowest power first, skipping zero terms."""
    terms = []
    for k, c in enumerate(coeffs):
        if c == 0:
            continue
        if k == 0:
            terms.append(str(c))
        else:
            head = "" if c == 1 else str(c)
            terms.append(f"{head}{var}{sup(k) if k > 1 else ''}")
    return " + ".join(terms) if terms else "0"


def eq(text, size=30, color=INK, bold=False):
    return T(text, size, color, bold)


def pts(first, title, items, sub=None, chars=56, size=32, y=None, gap=0.42):
    """A slide whose points arrive one at a time."""
    @slide(first, title, sub)
    def build(s):
        rows = bullets(items, chars, size, gap=gap)
        rows.move_to([-7.0 + rows.width / 2, 0 if y is None else y, 0])
        for row in rows:
            yield [FadeIn(row, shift=RIGHT * 0.15)]
    return build


def cards(first, title, items, sub=None, w=None, h=2.3, size=27, y=-0.3, note=None):
    """A row of colored cards, given as (text, color) pairs, arriving one at a time."""
    @slide(first, title, sub)
    def build(s):
        width = w or min(4.6, (14.6 - 0.35 * (len(items) - 1)) / len(items))
        row = VGroup(*[card(t, width, h, c, size) for t, c in items]).arrange(RIGHT, buff=0.35)
        at(row, 0, y)
        for c in row:
            yield [FadeIn(c, shift=UP * 0.2)]
        if note:
            yield [FadeIn(caption(note, y=y - h / 2 - 0.85, color=INK, size=28, chars=78))]
    return build


def cells(vals, w=0.8, color=BLUE, size=26, buff=0.08):
    """A row of coefficient cells."""
    return VGroup(*[card(str(v), w, w, color, size) for v in vals]).arrange(RIGHT, buff=buff)


def powers(row, start=0, size=20, reverse=False):
    """Power labels under a row of cells."""
    n = len(row)
    return VGroup(*[T(f"X{sup(start + (n - 1 - i if reverse else i))}", size, MUTED).next_to(c, DOWN, buff=0.1)
                    for i, c in enumerate(row)])


def labeled(label, row, color=BLUE, size=26, buff=0.3):
    lab = T(label, size, color, True).next_to(row, LEFT, buff=buff)
    return lab


def mat(rows, size=26, color=INK, w=0.62, h=0.5):
    """A small matrix as a grid of numbers inside brackets."""
    grid = VGroup(*[VGroup(*[T(str(v), size, color) for v in r]) for r in rows])
    for i, r in enumerate(grid):
        for j, v in enumerate(r):
            v.move_to([j * w, -i * h, 0])
    left = Line(grid.get_corner(UL) + [-0.15, 0.12, 0], grid.get_corner(DL) + [-0.15, -0.12, 0], color=MUTED, stroke_width=3)
    right = Line(grid.get_corner(UR) + [0.15, 0.12, 0], grid.get_corner(DR) + [0.15, -0.12, 0], color=MUTED, stroke_width=3)
    return VGroup(grid, left, right)


def value_table(headers, rows, colw=1.6, rowh=0.62, size=26, head_color=MUTED):
    """A plain table of short values: returns (header row, list of body rows)."""
    head = VGroup(*[T(h, size - 2, head_color, True).move_to([j * colw, 0, 0]) for j, h in enumerate(headers)])
    body = []
    for i, r in enumerate(rows):
        body.append(VGroup(*[(v if isinstance(v, Mobject) else T(str(v), size, INK)).move_to([j * colw, -(i + 1) * rowh, 0])
                             for j, v in enumerate(r)]))
    return head, body



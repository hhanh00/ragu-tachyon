def at(mob, x, y):
    return mob.move_to([x, y, 0])


def pts(first, title, items, sub=None, chars=56, size=32, y=None, gap=0.42):
    """A slide whose points arrive one at a time."""
    @slide(first, title, sub)
    def build(s):
        rows = bullets(items, chars, size, gap=gap)
        rows.move_to([-7.0 + rows.width / 2, 0 if y is None else y, 0])
        for row in rows:
            yield [FadeIn(row, shift=RIGHT * 0.15)]
    return build


def cards(first, title, items, sub=None, w=None, h=2.3, size=27, y=-0.3, note=None):
    """A row of colored cards, given as (text, color) pairs, arriving one at a time."""
    @slide(first, title, sub)
    def build(s):
        width = w or min(4.6, (14.6 - 0.35 * (len(items) - 1)) / len(items))
        row = VGroup(*[card(t, width, h, c, size) for t, c in items]).arrange(RIGHT, buff=0.35)
        at(row, 0, y)
        for c in row:
            yield [FadeIn(c, shift=UP * 0.2)]
        if note:
            yield [FadeIn(caption(note, y=y - h / 2 - 0.85, color=INK, size=28, chars=78))]
    return build


def claim(text, color=BLUE, size=24, label=None):
    """A claim as a chip (point, challenges), with an optional label above."""
    c = chip(text, color, size=size)
    if label:
        return VGroup(c, T(label, 22, MUTED).next_to(c, UP, buff=0.12))
    return c


def note(text, x, y, color=INK, size=26, chars=40, align=ORIGIN):
    return at(W(text, chars, size, color, align=align), x, y)


def check_eq(left, right, color=TEAL, size=28, y=0, x=0):
    """Two sides of a final check, with an equals sign."""
    return at(VGroup(code(left, size, INK), T("=", size + 4, color, True), code(right, size, INK)).arrange(RIGHT, buff=0.3), x, y)


def xmark(mob, color=RED, size=0.42, buff=0.25):
    """A red cross beside a rejected value."""
    return cross(Square(size), color, 6).next_to(mob, RIGHT, buff=buff)


def merge_box(label="merge", w=2.4, h=1.3, size=28):
    return card(label, w, h, ORANGE, size)


def ipa_check(y=0.4):
    """The final check of the inner product argument, as labelled boxes."""
    left = card("statement point\n+ weighted cross terms", 5.0, 1.6, BLUE, 26)

def gate_rows(y=0.2, show=2):
    rows = VGroup()
    specs = [("stage mask", {0, 1}), ("final mask", {0, 2, 3})]
    for k, (name, free) in enumerate(specs[:show]):
        yy = y - k * 1.3
        label = lft(T(name, 26, INK), -6.6, yy)
        cells = VGroup(*[card(f"gate {g}", 1.9, 0.9, TEAL if g in free else MUTED, 23) for g in range(4)]).arrange(RIGHT, buff=0.2)
        lft(cells, -4.4, yy)
        for g in range(4):
            if g not in free:
                cells[g][0].set_fill(MUTED, 0.3)
        rows.add(VGroup(label, cells))
    return rows



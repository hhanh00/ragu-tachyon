def grid(cell=0.62, x=-2.6, y=0.0, stage=3):
    """The 6x6 grid of products: left vector i (row) with right vector j (column)."""
    cells = VGroup()
    for i in range(6):
        for j in range(6):
            same = i // 3 == j // 3
            if i == j:
                col, op = TEAL, 0.5
            elif same:
                col, op = ORANGE, 0.45
            else:
                col, op = ORANGE, 0.12
            if stage == 0:
                col, op = MUTED, 0.08
            sq = Square(cell, stroke_color=WHITE, stroke_width=2, fill_color=col, fill_opacity=op)
            sq.move_to([x + (j - 2.5) * cell, y - (i - 2.5) * cell, 0])
            cells.add(sq)
    rl = VGroup(*[T(str(i), 20, MUTED).move_to([x - 3 * cell - 0.3, y - (i - 2.5) * cell, 0]) for i in range(6)])
    cl = VGroup(*[T(str(j), 20, MUTED).move_to([x + (j - 2.5) * cell, y + 3 * cell + 0.3, 0]) for j in range(6)])
    return cells, rl, cl



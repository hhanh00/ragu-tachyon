def at(mob, x, y):
    return mob.move_to([x, y, 0])


def lft(mob, x, y):
    """Place a mobject with its left edge at x."""
    return mob.move_to([x + mob.width / 2, y, 0])


def eq(text, size=30, color=INK):
    return code(text, size, color)


def pts(first, title, items, sub=None, chars=56, size=32, y=None, gap=0.42):
    """A slide whose points arrive one at a time."""
    @slide(first, title, sub)
    def build(s):
        rows = bullets(items, chars, size, gap=gap)
        rows.move_to([-7.0 + rows.width / 2, 0 if y is None else y, 0])
        for row in rows:
            yield [FadeIn(row, shift=RIGHT * 0.15)]
    return build


def cards(first, title, items, sub=None, w=None, h=2.3, size=27, y=-0.3, note=None):
    """A row of colored cards, given as (text, color) pairs, arriving one at a time."""
    @slide(first, title, sub)
    def build(s):
        width = w or min(4.6, (14.6 - 0.35 * (len(items) - 1)) / len(items))
        row = VGroup(*[card(t, width, h, c, size) for t, c in items]).arrange(RIGHT, buff=0.35)
        at(row, 0, y)
        for c in row:
            yield [FadeIn(c, shift=UP * 0.2)]
        if note:
            yield [FadeIn(caption(note, y=y - h / 2 - 0.85, color=INK, size=28, chars=78))]
    return build


def eqs(first, title, lines, sub=None, y=1.2, gap=0.95, size=30, note=None, note_color=INK):
    """Equations that arrive one at a time, each a (text, color) pair."""
    @slide(first, title, sub)
    def build(s):
        for k, (t, c) in enumerate(lines):
            yield [FadeIn(at(eq(t, size, c), 0, y - k * gap), shift=UP * 0.15)]
        if note:
            yield [FadeIn(caption(note, y=y - len(lines) * gap - 0.4, color=note_color, size=28, chars=74))]
    return build


def chain(items, y=0.3, w=2.6, h=1.4, size=24, buff=0.55):
    """A row of cards joined by arrows."""
    row = VGroup(*[card(t, w, h, c, size) for t, c in items]).arrange(RIGHT, buff=buff)
    at(row, 0, y)
    arrows = [arrow(row[i], row[i + 1]) for i in range(len(items) - 1)]
    return row, arrows


def table(head, rows, xs, y0=1.9, dy=0.62, size=25, colors=None):
    """Rows of text placed by left edges. Returns the header and a list of rows."""
    h = VGroup(*[lft(T(t, size - 2, MUTED, True), x, y0) for t, x in zip(head, xs)])
    out = []
    for i, r in enumerate(rows):
        c = colors[i] if colors else INK
        out.append(VGroup(*[lft(T(t, size, c if k else MUTED), x, y0 - (i + 1) * dy) for k, (t, x) in enumerate(zip(r, xs))]))
    return h, out



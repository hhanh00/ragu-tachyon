def at(mob, x, y):
    return mob.move_to([x, y, 0])


def pts(first, title, items, sub=None, chars=56, size=31, y=None, gap=0.42):
    """A slide whose points arrive one at a time."""
    @slide(first, title, sub)
    def build(s):
        rows = bullets(items, chars, size, gap=gap)
        rows.move_to([-7.0 + rows.width / 2, -0.2 if y is None else y, 0])
        for row in rows:
            yield [FadeIn(row, shift=RIGHT * 0.15)]
    return build


def cards(first, title, items, sub=None, w=None, h=2.3, size=27, y=-0.3, note=None, groups=None):
    """A row of colored cards, given as (text, color) pairs, arriving one at a time or in the given group sizes."""
    @slide(first, title, sub)
    def build(s):
        width = w or min(4.6, (14.6 - 0.35 * (len(items) - 1)) / len(items))
        row = VGroup(*[card(t, width, h, c, size) for t, c in items]).arrange(RIGHT, buff=0.35)
        at(row, 0, y)
        k = 0
        for g in groups or [1] * len(items):
            yield [FadeIn(c, shift=UP * 0.2) for c in row[k:k + g]]
            k += g
        if note:
            yield [FadeIn(caption(note, y=y - h / 2 - 0.85, color=INK, size=28, chars=78))]
    return build


def versus(first, title, left, right, sub=None, note=None, lc=MUTED, rc=TEAL, h=2.6, size=26, y=0.1):
    """Two sources side by side, then the site's reading."""

def chain_diagram(y=0.0):
    """The hash chain from the keys to the nullifiers."""
    n = {}
    n["ak"] = at(chip("ak", PURPLE, size=24), -6.2, y + 1.9)
    n["nk"] = at(chip("nk", PURPLE, size=24), -6.2, y + 0.2)
    n["pk"] = at(chip("pk", BLUE, size=24), -3.0, y + 1.3)
    n["v"] = at(chip("v", PURPLE, size=24), -2.0, y + 2.4)
    n["rcm"] = at(chip("rcm", PURPLE, size=24), 0.0, y + 2.4)
    n["psi"] = at(chip("psi", PURPLE, size=24), -3.0, y - 1.3)

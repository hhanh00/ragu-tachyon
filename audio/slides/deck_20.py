def ggm_tree(y0=-2.3, dy=1.35):
    """A depth-three binary tree; nodes keyed by prefix."""
    nodes, edges = {}, VGroup()
    nodes[""] = at(chip("seed", PURPLE, size=20), 0, y0 + 3 * dy)
    for d in (1, 2, 3):
        for k in range(2 ** d):
            p = format(k, f"0{d}b")
            x = (k - (2 ** d - 1) / 2) * (13.0 / 2 ** d) * (0.95 if d == 3 else 1)
            nodes[p] = at(chip(p, PURPLE if d < 3 else BLUE, size=20), x, y0 + (3 - d) * dy)
            edges.add(Line(nodes[p[:-1]].get_bottom(), nodes[p].get_top(), color=LINE, stroke_width=3))
    return nodes, edges



def tg_table(show_hyp=False, y=0.0):
    """The nine sorted tachygrams of the example bundle, with the hypothetical pads."""
    data = [(13229, 38763, "output 2, pad"), (24937, None, "output 2, cm"), (30698, None, "spend 2, nf 8"), (31831, None, "output 1, cm"),
            (40944, None, "spend 2, nf 7"), (46656, 52667, "output 1, pad"), (55113, None, "spend 1, nf 7"), (55356, None, "fee change note, cm"),
            (61177, None, "spend 1, nf 8")]
    rows = VGroup()
    for i, (v, h, who) in enumerate(data):
        yy = y + 1.95 - i * 0.5
        real = at(code(str(v), 23, BLUE), -6.3, yy)
        hyp = at(code(str(h) if h else str(v), 23, RED if h else MUTED), -4.1, yy)
        lab = T(who, 22, MUTED)
        lab.move_to([-2.4 + lab.width / 2, yy, 0])
        rows.add(VGroup(real, hyp, lab))
    heads = VGroup(at(T("published", 22, BLUE, True), -6.3, y + 2.5), at(T("if pad = H(cm)", 22, RED, True), -4.1, y + 2.5),
                   at(T("known only to the parties", 22, MUTED, True), -0.75, y + 2.5))
    return rows, heads



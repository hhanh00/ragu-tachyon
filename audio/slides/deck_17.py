def at(mob, x, y):
    return mob.move_to([x, y, 0])


def pts(first, title, items, sub=None, chars=56, size=32, y=None, gap=0.42):
    """A slide whose points arrive one at a time."""
    @slide(first, title, sub)
    def build(s):
        rows = bullets(items, chars, size, gap=gap)
        rows.move_to([-7.0 + rows.width / 2, 0 if y is None else y, 0])
        for row in rows:
            yield [FadeIn(row, shift=RIGHT * 0.15)]
    return build


def cards(first, title, items, sub=None, w=None, h=2.3, size=27, y=-0.3, note=None):
    """A row of colored cards, given as (text, color) pairs, arriving one at a time."""
    @slide(first, title, sub)
    def build(s):
        width = w or min(4.6, (14.6 - 0.35 * (len(items) - 1)) / len(items))
        row = VGroup(*[card(t, width, h, c, size) for t, c in items]).arrange(RIGHT, buff=0.35)
        at(row, 0, y)
        for c in row:
            yield [FadeIn(c, shift=UP * 0.2)]
        if note:
            yield [FadeIn(caption(note, y=y - h / 2 - 0.85, color=INK, size=28, chars=78))]
    return build


def grid(vals, color=BLUE, x=0, y=0, cw=0.95, ch=0.56, size=24, name=None, gap=0.1):
    """Four gates of four wires. vals maps (gate, wire) to a value; missing cells are zero."""
    g = VGroup()
    cells = {}
    for r in range(4):
        for c in range(4):
            v = vals.get((r, c))
            cell = chip(v if v else "0", color if v else LINE, w=cw, h=ch, size=size)
            at(cell, x + (c - 1.5) * (cw + 0.1), y + (1.5 - r) * (ch + gap))
            cells[(r, c)] = cell
            g.add(cell)
    rows = VGroup(*[T(f"gate {r}", 21, MUTED).next_to(cells[(r, 0)], LEFT, buff=0.18) for r in range(4)])
    cols = VGroup(*[T(f"w{c + 1}", 20, MUTED).next_to(cells[(0, c)], UP, buff=0.12) for c in range(4)])
    g.add(rows, cols)
    if name:
        lab = T(name, 25, color, True).next_to(cols, UP, buff=0.15)
        g.add(lab)
    g.cells = cells
    return g


def bar(vals, color=BLUE, x=0, y=0, w=0.74, h=0.5, size=19, index=False, zero=LINE):
    """A list of sixteen entries in one row."""
    g = VGroup()
    cells = []
    for i, v in enumerate(vals):
        cell = chip(str(v), color if v else zero, w=w, h=h, size=size)
        at(cell, x + (i - (len(vals) - 1) / 2) * (w + 0.08), y)
        cells.append(cell)
        g.add(cell)
    if index:
        g.add(*[T(str(i), 16, MUTED).next_to(c, DOWN, buff=0.08) for i, c in enumerate(cells)])
    g.cells = cells
    return g



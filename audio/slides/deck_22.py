def table(rows, xs, y0, dy=0.62, size=24, head=True, colors=None):
    """Rows of text placed at fixed column centers; the first row is a bold header."""
    g = VGroup()
    for r, row in enumerate(rows):
        line = VGroup()
        for c, (txt, x) in enumerate(zip(row, xs)):
            col = (colors[r][c] if colors and colors[r] and colors[r][c] else (MUTED if head and r == 0 else INK))
            line.add(at(T(str(txt), size, col, bold=head and r == 0), x, y0 - r * dy))
        g.add(line)
    return g



def stack(items, box, size=24, color=BLUE):
    """Chips laid out top to bottom inside a transcript box."""
    chips = VGroup(*[chip(t, color, size=size) for t in items]).arrange(DOWN, buff=0.14)
    chips.move_to(box[0]).align_to(box[0], UP).shift(DOWN * 0.25)
    return chips


def state_cells(vals=("0", "0", "0"), y=0.2, x=0, w=1.5, labels=True):
    cells = VGroup(*[card(v, w, 1.0, BLUE if i < 2 else MUTED, 30) for i, v in enumerate(vals)]).arrange(RIGHT, buff=0.18)
    at(cells, x, y)

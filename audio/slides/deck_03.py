def zero_grid(fn, x0=-3.0, y0=-0.4, step=0.112, r=0.034):
    """The 43 by 43 grid of the toy field, with zeros of fn marked."""
    dots, zeros = VGroup(), VGroup()
    for x in range(43):
        for y in range(43):
            p = [x0 + (x - 21) * step, y0 + (y - 21) * step, 0]
            if fn(x, y) % 43 == 0:
                zeros.add(Dot(p, radius=r * 1.5, color=RED))
            else:
                dots.add(Dot(p, radius=r * 0.7, color=LINE))
    frame = SurroundingRectangle(dots, color=LINE, buff=0.08, stroke_width=2)
    return dots, zeros, frame



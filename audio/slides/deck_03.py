def msg(text, y, right=True, color=BLUE, size=26):
    """A message passing between the two parties at height y."""
    a, b = (-3.7, 3.7) if right else (3.7, -3.7)
    ar = Arrow([a, y, 0], [b, y, 0], buff=0, color=color, stroke_width=4, tip_length=0.2)
    lab = code(text, size, color).next_to(ar, UP, buff=0.1)
    return VGroup(ar, lab)



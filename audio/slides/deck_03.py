    rate = T("rate", 23, BLUE, True).next_to(VGroup(cells[0], cells[1]), DOWN, buff=0.15)
    cap = T("capacity", 23, MUTED, True).next_to(cells[2], DOWN, buff=0.15)
    return cells, VGroup(rate, cap)



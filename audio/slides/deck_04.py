def at(mob, x, y):
    return mob.move_to([x, y, 0])


def pts(first, title, items, sub=None, chars=56, size=32, y=None, gap=0.42):
    """A slide whose points arrive one at a time."""
    @slide(first, title, sub)
    def build(s):
        rows = bullets(items, chars, size, gap=gap)
        rows.move_to([-7.0 + rows.width / 2, 0 if y is None else y, 0])
        for row in rows:
            yield [FadeIn(row, shift=RIGHT * 0.15)]
    return build


def cards(first, title, items, sub=None, w=None, h=2.3, size=27, y=-0.3, note=None):
    """A row of colored cards, given as (text, color) pairs, arriving one at a time."""
    @slide(first, title, sub)
    def build(s):
        width = w or min(4.6, (14.6 - 0.35 * (len(items) - 1)) / len(items))
        row = VGroup(*[card(t, width, h, c, size) for t, c in items]).arrange(RIGHT, buff=0.35)
        at(row, 0, y)
        for c in row:
            yield [FadeIn(c, shift=UP * 0.2)]
        if note:
            yield [FadeIn(caption(note, y=y - h / 2 - 0.85, color=INK, size=28, chars=78))]
    return build


def eq(text, size=34, color=INK):
    return code(text, size, color)


def cells(vals, y=0.0, w=1.15, h=0.95, color=BLUE, size=30, labels=None, lab_color=MUTED, x=0.0, buff=0.2, colors=None, below=False, lab_size=22):
    """A row of value boxes, with optional labels above each box."""
    row = VGroup(*[card(str(v), w, h, (colors[i] if colors else color), size) for i, v in enumerate(vals)]).arrange(RIGHT, buff=buff)
    at(row, x, y)
    labs = VGroup()
    if labels:
        for l, c in zip(labels, row):
            labs.add(code(l, lab_size, lab_color).next_to(c, DOWN if below else UP, buff=0.12))
    return row, labs


def pair_arcs(row, pairs, color=MUTED, width=4, colors=None):
    """Arcs under a row of boxes, joining each pair of partner positions."""
    arcs = VGroup()
    for k, (i, j) in enumerate(pairs):
        arcs.add(ArcBetweenPoints(row[i].get_bottom() + DOWN * 0.05, row[j].get_bottom() + DOWN * 0.05, angle=PI * 0.55,
                                  color=colors[k] if colors else color, stroke_width=width))
    return arcs


def gate(left, right, out, x=0.0, y=0.0, color=BLUE, size=28):
    """A multiplication gate: two inputs into a box, one output out of it."""
    box = at(card("×", 1.3, 1.3, ORANGE, 40), x, y)
    a = at(chip(str(left), color, size=size), x - 2.3, y + 0.55)
    b = at(chip(str(right), color, size=size), x - 2.3, y - 0.55)
    c = at(chip(str(out), color, size=size), x + 2.3, y)
    arrows = VGroup(arrow(a.get_right(), box.get_left() + UP * 0.3, buff=0.08), arrow(b.get_right(), box.get_left() + DOWN * 0.3, buff=0.08),
                    arrow(box, c, buff=0.08))
    return VGroup(a, b, box, c, arrows)



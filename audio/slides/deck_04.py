def monomial_grid(x0=-5.6, y0=-2.6, step=0.58):
    """Cells for z-powers 0..7 across and y-powers 0..7 up, colored by which part can reach them."""
    grid = VGroup()
    for zi in range(8):
        for yi in range(8):
            if yi == 0 and 2 <= zi <= 5:
                col, op = BLUE, 0.75
            elif yi == 0 and zi in (0, 1, 6, 7):
                col, op = ORANGE, 0.75
            elif zi == 0:
                col, op = MUTED, 0.55
            else:
                col, op = WHITE, 0
            sq = Square(step * 0.9, stroke_color=LINE, stroke_width=2, fill_color=col, fill_opacity=op)
            sq.move_to([x0 + zi * step, y0 + yi * step, 0])
            grid.add(sq)
    zl = VGroup(*[T(str(k), 22, MUTED).move_to([x0 + k * step, y0 - 0.5, 0]) for k in range(8)])
    yl = VGroup(*[T(str(k), 22, MUTED).move_to([x0 - 0.5, y0 + k * step, 0]) for k in range(8)])
    zt = T("power of the gate challenge z", 23, MUTED).move_to([x0 + 3.5 * step, y0 - 0.95, 0])
    yt = T("power of y", 23, MUTED).rotate(PI / 2).move_to([x0 - 1.0, y0 + 3.5 * step, 0])
    return grid, VGroup(zl, yl, zt, yt)



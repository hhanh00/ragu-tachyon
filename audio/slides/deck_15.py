def at(mob, x, y):
    return mob.move_to([x, y, 0])


def settle(s, steps):
    """Apply build steps instantly, so a continuation slide starts from their final state."""
    for step in steps:
        for a in step:
            a = prepare_animation(a)
            s.add(*leaves(a))
            a.begin()
            a.finish()
            a.clean_up_from_scene(s)


def leaves(a):
    """The mobjects an animation shows, looking inside animation groups."""
    if hasattr(a, "animations"):
        return [m for sub in a.animations for m in leaves(sub)]
    return [a.mobject]


def two(first1, first2, title, k, sub=None, title2=None):
    """Register one build as two slides: the first k steps, then the rest from that state."""
    def register(fn):
        @slide(first1, title, sub)
        def part1(s):
            for i, step in enumerate(fn(s)):
                if i >= k:
                    break
                yield step

        @slide(first2, title2 or title, sub)
        def part2(s):
            g = fn(s)
            head = [next(g) for _ in range(k)]
            if not isinstance(s, Dry):
                settle(s, head)
            yield from g
        return fn
    return register



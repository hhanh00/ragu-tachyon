def seq(rows, y0=1.5, dy=0.82, size=24):
    """A message diagram. Each row is (sender, text, color) with sender 'P' or 'V'."""
    left = at(T("Prover", 28, BLUE, True), -5.6, y0 + 0.75)
    right = at(T("Verifier", 28, ORANGE, True), 5.6, y0 + 0.75)
    lines = VGroup(DashedLine([-5.6, y0 + 0.4, 0], [-5.6, y0 - dy * len(rows), 0], color=LINE),
                   DashedLine([5.6, y0 + 0.4, 0], [5.6, y0 - dy * len(rows), 0], color=LINE))
    items = []
    for k, (who, text, color) in enumerate(rows):
        yy = y0 - dy * k - 0.15
        a, b = ([-5.4, yy, 0], [5.4, yy, 0]) if who == "P" else ([5.4, yy, 0], [-5.4, yy, 0])
        ar = Arrow(a, b, buff=0, color=color, stroke_width=3, tip_length=0.18, max_tip_length_to_length_ratio=0.05)
        lab = T(text, size, color).move_to([0, yy + 0.26, 0])
        items.append(VGroup(ar, lab))
    return VGroup(left, right, lines), items



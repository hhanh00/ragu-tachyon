def epoch_brackets(nodes, y, spans=((0, 3, 0), (4, 4, 1), (5, 7, 2), (8, 9, 3))):
    g = VGroup()
    for a, b, e in spans:
        if b >= len(nodes):
            continue
        left, right = nodes[a].get_left()[0] - 0.05, nodes[b].get_right()[0] + 0.05
        line = Line([left, y, 0], [right, y, 0], color=MUTED, stroke_width=3)
        ticks = VGroup(Line([left, y, 0], [left, y + 0.15, 0], color=MUTED, stroke_width=3),
                       Line([right, y, 0], [right, y + 0.15, 0], color=MUTED, stroke_width=3))
        g.add(VGroup(line, ticks, T(f"epoch {e}", 20, MUTED).next_to(line, DOWN, buff=0.1)))
    return g


def poly_row(entries, y=0.0, size=26, color=BLUE, buff=0.25):
    row = VGroup(*[val(e, color, size) for e in entries]).arrange(RIGHT, buff=buff)
    return at(row, 0, y)


def table(rows, widths, x0=-6.6, y0=1.6, dy=0.62, size=24, colors=None):
    """Rows of text in fixed columns. The first row is a header in MUTED."""
    g = VGroup()
    for r, row in enumerate(rows):
        line = VGroup()
        x = x0
        for c, (cell, w) in enumerate(zip(row, widths)):
            color = MUTED if r == 0 else (colors[r][c] if colors and colors[r] and colors[r][c] else INK)
            t = T(str(cell), size, color, r == 0)
            t.move_to([x + t.width / 2, y0 - r * dy, 0])
            line.add(t)
            x += w
        g.add(line)
    return g



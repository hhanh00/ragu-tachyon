def merkle(x=-3.6, y=-1.6, highlight=True):
    leaves = at(VGroup(*[card(None, 0.7, 0.5, BLUE) for _ in range(8)]).arrange(RIGHT, buff=0.25), x, y)
    lvl = [list(leaves)]
    edges = VGroup()
    for d in range(3):
        nxt = []
        for k in range(0, len(lvl[-1]), 2):
            a, b = lvl[-1][k], lvl[-1][k + 1]
            n = at(card(None, 0.7, 0.5, MUTED), (a.get_x() + b.get_x()) / 2, y + (d + 1) * 1.2)
            edges.add(Line(a.get_top(), n.get_bottom(), color=LINE, stroke_width=3), Line(b.get_top(), n.get_bottom(), color=LINE, stroke_width=3))
            nxt.append(n)
        lvl.append(nxt)
    return leaves, lvl, edges



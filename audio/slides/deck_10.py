def lopsided(x0=-6.4, y0=-2.3, n=8, dx=0.85, dy=0.6):
    nodes = VGroup(*[Dot([x0 + k * dx, y0 + k * dy, 0], radius=0.12, color=ORANGE if k == 0 else BLUE) for k in range(n)])
    units = VGroup(*[Dot([x0 + k * dx + 0.5, y0 + k * dy - 0.45, 0], radius=0.08, color=MUTED) for k in range(1, n)])
    edges = VGroup(*[Line(nodes[k].get_center(), nodes[k + 1].get_center(), color=LINE, stroke_width=3) for k in range(n - 1)])
    uedges = VGroup(*[Line(u.get_center(), nodes[k + 1].get_center(), color=LINE, stroke_width=2) for k, u in enumerate(units)])
    return nodes, units, edges, uedges


def balanced(x0=3.2, y0=-2.3, dx=0.62, dy=0.95):
    levels = [[Dot([x0 + (i - 3.5) * dx, y0, 0], radius=0.11, color=ORANGE) for i in range(8)]]
    edges = VGroup()
    while len(levels[-1]) > 1:
        prev = levels[-1]
        up = []
        for i in range(0, len(prev), 2):
            d = Dot([(prev[i].get_x() + prev[i + 1].get_x()) / 2, prev[0].get_y() + dy, 0], radius=0.11, color=BLUE)
            edges.add(Line(prev[i].get_center(), d.get_center(), color=LINE, stroke_width=3), Line(prev[i + 1].get_center(), d.get_center(), color=LINE, stroke_width=3))
            up.append(d)
        levels.append(up)
    return VGroup(*[d for l in levels for d in l]), edges



def at(mob, x, y):
    return mob.move_to([x, y, 0])


def pts(first, title, items, sub=None, chars=56, size=32, y=None, gap=0.42):
    """A slide whose points arrive one at a time."""
    @slide(first, title, sub)
    def build(s):
        rows = bullets(items, chars, size, gap=gap)
        rows.move_to([-7.0 + rows.width / 2, 0 if y is None else y, 0])
        for row in rows:
            yield [FadeIn(row, shift=RIGHT * 0.15)]
    return build


def cards(first, title, items, sub=None, w=None, h=2.3, size=27, y=-0.3, note=None):
    """A row of colored cards, given as (text, color) pairs, arriving one at a time."""
    @slide(first, title, sub)
    def build(s):
        width = w or min(4.6, (14.6 - 0.35 * (len(items) - 1)) / len(items))
        row = VGroup(*[card(t, width, h, c, size) for t, c in items]).arrange(RIGHT, buff=0.35)
        at(row, 0, y)
        for c in row:
            yield [FadeIn(c, shift=UP * 0.2)]
        if note:
            yield [FadeIn(caption(note, y=y - h / 2 - 0.85, color=INK, size=28, chars=78))]
    return build


def chain_row(values=CHAIN, y=0.4, dx=2.5, size=30, color=BLUE, labels=True):
    """States as chips joined by arrows labelled F."""
    chips = VGroup(*[at(chip(str(v), color, size=size, h=0.8, w=1.3), (i - (len(values) - 1) / 2) * dx, y)
                     for i, v in enumerate(values)])
    arrows = VGroup(*[arrow(chips[i], chips[i + 1], ORANGE) for i in range(len(values) - 1)])
    fs = VGroup(*[T("F", 24, ORANGE, True).next_to(a, UP, buff=0.08) for a in arrows])
    names = VGroup(*[T(f"z{i}", 22, MUTED).next_to(c, DOWN, buff=0.15) for i, c in enumerate(chips)]) if labels else VGroup()
    return chips, arrows, fs, names


def circuit(label, color=ORANGE, w=2.8, h=1.5, size=26):
    return card(label, w, h, color, size)


def gate_row(a, b, c, what, color, y, x=-0.4, size=30):
    """A multiplication gate a x b = c, with a note on what it computes."""
    g = VGroup(code(f"{a} × {b} = {c}", size, color)).move_to([x - 2.6, y, 0])
    note = T(what, 24, MUTED).move_to([x + 2.6, y, 0])
    note.shift(RIGHT * (note.width / 2 - 2.0 + 0.0))
    return VGroup(g, note)


def relation_box(y=0.2, two=False):
    pub = card("public\nnext state", 3.2, 1.6, BLUE, 26)
    wit = card("witness\nleft and right states, proofs" if two else "witness\ncurrent state, old proof", 4.6 if two else 4.2, 1.6, MUTED, 26)
    chk = card("checks\nstep, and verifier on each child" if two else "checks\nstep, and verifier", 4.6, 1.6, TEAL, 26)
    row = VGroup(pub, wit, chk).arrange(RIGHT, buff=0.3)
    return at(row, 0, y)


def bar(value, scale, color, h=0.5):
    return Rectangle(width=max(value * scale, 0.04), height=h, stroke_width=0, fill_color=color, fill_opacity=0.85)


def hdr(l, h, s, color=BLUE, size=24):
    return chip(f"({l}, {h}, {s})", color, size=size)


def growth_axes(y_max=75, x=-2.8, y=-0.55, w=7.6, h=4.6):
    ax = Axes(x_range=[0, 5, 1], y_range=[0, y_max, 10 if y_max > 30 else 5], x_length=w, y_length=h, tips=False,
              axis_config={"color": LINE, "stroke_width": 3, "include_ticks": False}).move_to([x, y, 0])
    xl = VGroup(*[T(str(i), 22, MUTED).next_to(ax.c2p(i, 0), DOWN, buff=0.15) for i in range(6)])
    lab = T("level", 22, MUTED).next_to(ax, DOWN, buff=0.5)
    yl = T("log2 of circuit size", 22, MUTED).rotate(PI / 2).next_to(ax, LEFT, buff=0.2)
    return ax, VGroup(xl, lab, yl)


